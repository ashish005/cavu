import { Component, OnInit, inject } from '@angular/core';
import { CommonModule } from '@angular/common';
import { FormsModule } from '@angular/forms';
import { skip } from 'rxjs/operators';
import { AiStudioService, StudioEntity } from '../../ai-studio.service';
import { DiscoveryOutputComponent } from '../output/discovery-output.component';

/** Discovery → Attributed Output (independent child route). */
@Component({
  selector: 'app-discovery-output-view',
  standalone: true,
  imports: [CommonModule, FormsModule, DiscoveryOutputComponent],
  template: `
  <div>
    <div class="page-head">
      <div><h1>Attributed Discovery Output</h1><p class="sub">Latest records generated by discovery runs — open any dossier</p></div>
      <button class="btn" (click)="loadOutput()">↻ Refresh</button>
    </div>
    <app-discovery-output [entities]="entities" [loading]="loading" [page]="page" [perPage]="perPage" [total]="total"
      (pageChange)="onPage($event)"></app-discovery-output>
  </div>`
})
export class DiscoveryOutputViewComponent implements OnInit {
  studio = inject(AiStudioService);
  entities: StudioEntity[] = []; loading = false; page = 1; perPage = 25; total = 0;

  ngOnInit() {
    this.loadOutput();
    this.studio.reloaded$.pipe(skip(1)).subscribe(() => this.loadOutput());
  }
  loadOutput() {
    this.loading = true;
    this.studio.listEntitiesPaged(undefined, this.page, this.perPage, 'Discovered').subscribe({
      next: p => { this.entities = p.items; this.total = p.totalCount; this.loading = false; },
      error: () => this.loading = false,
    });
  }
  onPage(e: { skip: number; take: number }) { this.perPage = e.take; this.page = Math.floor(e.skip / e.take) + 1; this.loadOutput(); }
}
